public class PosNeg{
	
  public static void main(String arg[]){
  	int a=Integer.parseInt(arg[0]);
  	
  	if(a>0 && a!=0){
  	System.out.println(a+" is positive");
  		}
  	else if((a<0 && a!=0)){
  	System.out.println(a+" is negative");
  		}
  	else{
  	System.out.println(a+" is zero!!!");
  	}	
  		}
	
	
	}
